import { defineConfig, globalIgnores } from "eslint/config";
import nextVitals from "eslint-config-next/core-web-vitals";
import nextTs from "eslint-config-next/typescript";

// Dependency rules from docs/engineering.md (rules 1 and 4).
const restrictImports = (patterns) => ({
  "@typescript-eslint/no-restricted-imports": ["error", { patterns }],
});

const convexRuntime = {
  group: ["@convex/**", "convex", "convex/**", "**/convex/**"],
  allowTypeImports: true,
  message: "Domain code is framework-free: import only types from Convex.",
};

const uiAndFramework = {
  group: ["@/features/**", "@/app/**", "@/components/**", "react", "react/**", "react-dom", "next", "next/**"],
  message: "Domain code is framework-free: no React, Next.js or UI imports.",
};

// Features may import their own audience and features/shared, never another audience (rule 4).
const otherAudiences = (audience) => ({
  regex: `^@/features/(?!shared/|${audience}/)`,
  message: `Code in features/${audience} doesn't import other audiences. Move shared code to features/shared, domain or components/ui.`,
});

const parentFolders = {
  group: ["../*"],
  message: "Import from outside this folder with an alias (@/… or @convex/…) so dependency rules can be checked.",
};

const convexInternals = {
  regex: "^@convex/(?!_generated/)",
  allowTypeImports: true,
  message: "The frontend talks to Convex through @convex/_generated/api; import only types from other Convex files.",
};

const frontendCode = {
  group: ["**/src/features/**", "**/src/app/**", "**/src/components/**", "@/features/**", "@/app/**", "@/components/**", "react", "react-dom", "next", "next/**"],
  message: "Convex functions don't import frontend code; share logic through src/domain.",
};

const eslintConfig = defineConfig([
  ...nextVitals,
  ...nextTs,
  {
    // Allows `const { _id, ...fields } = doc` to copy a document without its system fields.
    rules: { "@typescript-eslint/no-unused-vars": ["warn", { ignoreRestSiblings: true }] },
  },
  {
    files: ["src/domain/**/*.{ts,tsx}"],
    ignores: ["**/*.test.{ts,tsx}"],
    rules: restrictImports([convexRuntime, uiAndFramework, parentFolders]),
  },
  ...["host", "player", "tv", "shared"].map((audience) => ({
    files: [`src/features/${audience}/**/*.{ts,tsx}`],
    rules: restrictImports([otherAudiences(audience), parentFolders, convexInternals]),
  })),
  {
    files: ["convex/**/*.ts"],
    rules: restrictImports([frontendCode]),
  },
  // Override default ignores of eslint-config-next.
  globalIgnores([
    // Default ignores of eslint-config-next:
    ".next/**",
    "out/**",
    "build/**",
    "next-env.d.ts",
    // Generated by `npx convex dev`.
    "convex/_generated/**",
    // Coverage reports.
    "coverage/**",
  ]),
]);

export default eslintConfig;
